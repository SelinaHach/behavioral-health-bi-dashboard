"""Generates sql/02_reference_tables.sql from the TEDS-D 2023 codebook frequency tables."""
import csv, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
rows = list(csv.DictReader(open(ROOT / "ref" / "codebook_freqs.csv")))
by = {}
for r in rows:
    by.setdefault(r["variable"], []).append((int(r["code"]), r["label"], int(r["frequency"])))

ABBR = {1:'AL',2:'AK',4:'AZ',5:'AR',6:'CA',8:'CO',9:'CT',10:'DE',11:'DC',12:'FL',13:'GA',15:'HI',16:'ID',17:'IL',18:'IN',19:'IA',20:'KS',21:'KY',22:'LA',23:'ME',24:'MD',25:'MA',26:'MI',27:'MN',28:'MS',29:'MO',30:'MT',31:'NE',32:'NV',33:'NH',34:'NJ',35:'NM',36:'NY',37:'NC',38:'ND',39:'OH',40:'OK',41:'OR',42:'PA',44:'RI',45:'SC',46:'SD',47:'TN',48:'TX',49:'UT',50:'VT',51:'VA',53:'WA',54:'WV',55:'WI',56:'WY',72:'PR'}
SETTING_GROUP = {1:'Detox (24-hour)',2:'Detox (24-hour)',8:'Detox (ambulatory)',3:'Residential',4:'Residential',5:'Residential',6:'Intensive outpatient',7:'Outpatient'}
SUB_GROUP = {1:'None reported',2:'Alcohol',3:'Stimulants',10:'Stimulants',11:'Stimulants',12:'Stimulants',4:'Cannabis',5:'Opioids',6:'Opioids',7:'Opioids',8:'Hallucinogens',9:'Hallucinogens',13:'Sedatives/tranquilizers',14:'Sedatives/tranquilizers',15:'Sedatives/tranquilizers',16:'Sedatives/tranquilizers',17:'Other',18:'Other',19:'Other',-9:'Unknown'}
def los_band(c):
    if c == 1: return (1, '1 day')
    if c <= 7: return (2, '2-7 days')
    if c <= 14: return (3, '8-14 days')
    if c <= 30: return (4, '15-30 days')
    if c <= 32: return (5, '31-60 days')
    if c == 33: return (6, '61-90 days')
    if c <= 35: return (7, '91-180 days')
    if c == 36: return (8, '181-365 days')
    return (9, 'More than 1 year')
REASON_GROUP = {1:'Completed',2:'Dropped out',3:'Terminated by facility',4:'Transferred',5:'Other exit',6:'Other exit',7:'Other exit'}

def q(s): return "N'" + s.replace("'", "''") + "'"
out = []
w = out.append
w("-- 02_reference_tables.sql\n-- Step 2: lookup tables that turn number codes into names (for example STFIPS 4 = Arizona),\n-- plus the record counts printed in the SAMHSA codebook, used later by check DQ11.\n-- Values come from the TEDS-D 2023 codebook. This file is generated by build/gen_reference_sql.py.")
w("USE TEDS_BI;\nGO\n")
w("""-- Remove old versions of the tables so the file can be run again\nDROP TABLE IF EXISTS ref.state, ref.service_setting, ref.substance, ref.age_group, ref.sex, ref.race,
    ref.ethnicity, ref.length_of_stay, ref.discharge_reason, dq.codebook_frequency;
GO

-- One small table per code list
CREATE TABLE ref.state            (stfips SMALLINT PRIMARY KEY, state_name NVARCHAR(40) NOT NULL, state_abbr CHAR(2) NOT NULL);
CREATE TABLE ref.service_setting  (services_d SMALLINT PRIMARY KEY, setting_label NVARCHAR(80) NOT NULL, setting_group NVARCHAR(40) NOT NULL);
CREATE TABLE ref.substance        (sub_code SMALLINT PRIMARY KEY, substance_label NVARCHAR(60) NOT NULL, substance_group NVARCHAR(40) NOT NULL);
CREATE TABLE ref.age_group        (age SMALLINT PRIMARY KEY, age_label NVARCHAR(30) NOT NULL);
CREATE TABLE ref.sex              (sex SMALLINT PRIMARY KEY, sex_label NVARCHAR(50) NOT NULL);
CREATE TABLE ref.race             (race SMALLINT PRIMARY KEY, race_label NVARCHAR(60) NOT NULL);
CREATE TABLE ref.ethnicity        (ethnic SMALLINT PRIMARY KEY, ethnicity_label NVARCHAR(60) NOT NULL);
CREATE TABLE ref.length_of_stay   (los SMALLINT PRIMARY KEY, los_label NVARCHAR(30) NOT NULL, los_band_sort TINYINT NOT NULL, los_band NVARCHAR(30) NOT NULL);
CREATE TABLE ref.discharge_reason (reason SMALLINT PRIMARY KEY, reason_label NVARCHAR(70) NOT NULL, reason_group NVARCHAR(30) NOT NULL);
CREATE TABLE dq.codebook_frequency (variable_name NVARCHAR(30) NOT NULL, code SMALLINT NOT NULL, label NVARCHAR(100) NOT NULL,
    codebook_count INT NOT NULL, PRIMARY KEY (variable_name, code));
GO
""")
def ins(table, cols, vals):
    w(f"INSERT INTO {table} ({', '.join(cols)}) VALUES")
    w(",\n".join("  (" + ", ".join(v) + ")" for v in vals) + ";")
ins("ref.state", ["stfips","state_name","state_abbr"], [[str(c), q(l), q(ABBR[c])] for c,l,_ in by["STFIPS"]])
ins("ref.service_setting", ["services_d","setting_label","setting_group"], [[str(c), q(l), q(SETTING_GROUP[c])] for c,l,_ in by["SERVICES_D"]])
ins("ref.substance", ["sub_code","substance_label","substance_group"], [[str(c), q(l), q(SUB_GROUP[c])] for c,l,_ in by["SUB1"]])
ins("ref.age_group", ["age","age_label"], [[str(c), q(l)] for c,l,_ in by["AGE"]])
ins("ref.sex", ["sex","sex_label"], [[str(c), q(l)] for c,l,_ in by["SEX"]])
ins("ref.race", ["race","race_label"], [[str(c), q(l)] for c,l,_ in by["RACE"]])
ins("ref.ethnicity", ["ethnic","ethnicity_label"], [[str(c), q(l)] for c,l,_ in by["ETHNIC"]])
ins("ref.length_of_stay", ["los","los_label","los_band_sort","los_band"], [[str(c), q(l), str(los_band(c)[0]), q(los_band(c)[1])] for c,l,_ in by["LOS"]])
ins("ref.discharge_reason", ["reason","reason_label","reason_group"], [[str(c), q(l), q(REASON_GROUP[c])] for c,l,_ in by["REASON"]])
w("\n-- Record counts printed in the codebook (152 numbers). DQ11 compares them with the loaded data.")
ins("dq.codebook_frequency", ["variable_name","code","label","codebook_count"], [[q(v), str(c), q(l), str(f)] for v in by for c,l,f in by[v]])
w("GO")
(ROOT / "sql" / "02_reference_tables.sql").write_text("\n".join(out) + "\n")
print("rows:", {k: len(v) for k, v in by.items()})
